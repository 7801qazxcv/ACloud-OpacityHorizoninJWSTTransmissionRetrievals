"""Regenerate every manuscript number that depends on the emcee chains (v2).

Sources of truth (regenerated by stage18 / stage22, never hand-edited):
  experiments/stage18_posteriors.json  -> medians, 16-84 intervals, ESS,
                                          acceptance fractions, correlations
  experiments/stage22_convergence.json -> tau, ESS, half-chain agreement

Rewrites, in place, in sec5_validation.tex:
  1. the whole Table (tab:retrieval) block
  2. the numbers in the 'How far the chains can be trusted.' paragraph
  3. the correlation rho values quoted in the prose

Line endings are preserved as found (CRLF on this machine).  Prints OLD vs NEW.
"""
import io, json, os, re

BASE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(BASE)
SEC5 = os.path.join(ROOT, "paper", "sec5_validation.tex")
S18 = os.path.join(BASE, "stage18_posteriors.json")
S22 = os.path.join(BASE, "stage22_convergence.json")

LABEL = {"Rp": "$R_p$ ($R_{\\rm J}$)", "T": "$T$ (K)", "logZ": "$\\log Z$ (dex)",
         "CO_ratio": "C/O", "log_cloudtop_P": "$\\log_{10}\\Pc$ (Pa)"}
PRIOR = {"Rp": "$\\pm10\\%$", "T": "400--1600", "logZ": "$-2$--$3$",
         "CO_ratio": "0.05--2.0", "log_cloudtop_P": "0--6"}
DP = {"Rp": 3, "T": 0, "logZ": 2, "CO_ratio": 3, "log_cloudtop_P": 2}
ORDER = ["Rp", "T", "logZ", "CO_ratio", "log_cloudtop_P"]


def pm(v):
    return ("+" if v >= 0 else "-") + ("%.2f" % abs(v))


def main():
    d = json.load(open(S18, encoding="utf-8"))
    conv = json.load(open(S22, encoding="utf-8")) if os.path.exists(S22) else {}
    ir, op = d["IRonly_free"], d["optical_free"]

    raw = open(SEC5, "rb").read().decode("utf-8")
    t = raw.replace("\r\n", "\n")          # project files are LF-terminated

    # ---------------- 1. Table -------------------------------------------
    rows = []
    for p in ORDER:
        a, b = ir["stats"][p], op["stats"][p]
        f = lambda v, dp=DP[p]: ("%%.%df" % dp) % v
        rows.append("%s & %s & $%s\\,[%s,\\,%s]$ & $%s\\,[%s,\\,%s]$ \\\\"
                    % (LABEL[p], PRIOR[p], f(a["median"]), f(a["lo68"]), f(a["hi68"]),
                       f(b["median"]), f(b["lo68"]), f(b["hi68"])))
    e_ir = [ir["ess"][p]["ess"] for p in ORDER]
    e_op = [op["ess"][p]["ess"] for p in ORDER]
    c_ir, c_op = ir["correlations"], op["correlations"]
    fac = lambda p: ir["stats"][p]["iqr"] / op["stats"][p]["iqr"]

    new_table = "\n".join([
        "\\begin{table}[t]", "\\centering", "\\footnotesize",
        "\\caption{Posterior summaries from independent {\\sc emcee} retrievals of two",
        "published WASP-39\\,b spectra (equilibrium chemistry, identical uniform",
        "priors). Each entry is the marginal median with the 16--84\\% interval; the",
        "prior range is given in the second column. Acceptance fractions are $%.2f$" % ir["acceptance_fraction"],
        "(infrared-only) and $%.2f$ (optical), and effective sample sizes are" % op["acceptance_fraction"],
        "$%d$--$%d$ and $%d$--$%d$ per parameter respectively.}" % (min(e_ir), max(e_ir), min(e_op), max(e_op)),
        "\\label{tab:retrieval}", "\\begin{tabular}{llcc}", "\\toprule",
        "Parameter & prior range & G395H (IR-only) & NIRISS (optical) \\\\", "\\midrule"] +
        rows + ["\\bottomrule", "\\end{tabular}",
        "\\tablenotetext{}{Relative to their common uniform priors, the optical+NIR",
        "spectrum narrows $R_p$ by a factor $%.1f$, $T$ by $%.1f$, $\\logPc$ by $%.1f$ and" % (fac("Rp"), fac("T"), fac("log_cloudtop_P")),
        "$\\log Z$ by $%.1f$. Correlations differ strongly between the two fits and are" % fac("logZ"),
        "reported in the text: $\\rho(\\log Z,\\logPc)=%s$ (infrared-only) versus" % pm(c_ir["rho_logZ_log_cloudtop_P"]),
        "$%s$ (optical); $\\rho(R_p,T)=%s$ versus $%s$;" % (pm(c_op["rho_logZ_log_cloudtop_P"]), pm(c_ir["rho_Rp_T"]), pm(c_op["rho_Rp_T"])),
        "$\\rho(\\mathrm{C/O},\\log Z)=%s$ versus $%s$. The C/O posterior sits" % (pm(c_ir["rho_CO_ratio_logZ"]), pm(c_op["rho_CO_ratio_logZ"])),
        "against the lower prior bound in both fits and is flagged, not quoted as a",
        "measurement.}", "\\end{table}"])

    pat = re.compile(r"\\begin\{table\}\[t\]\n\\centering\n\\footnotesize\n\\caption\{Posterior summaries.*?\\end\{table\}", re.S)
    m = pat.search(t)
    print("OLD table numeric lines:")
    print("\n".join([l for l in m.group(0).split("\n") if "$" in l][:7]))
    print("NEW table numeric lines:")
    print("\n".join([l for l in new_table.split("\n") if "$" in l][:7]))
    t = t[:m.start()] + new_table + t[m.end():]

    # ---------------- 2. convergence paragraph -----------------------------
    if conv:
        tau = [v for r in conv.values() for v in r["tau"]]
        ess = [v for r in conv.values() for v in r["ess"]]
        half = [v for r in conv.values() for v in r["half_diff_in_sigma"]]
        spw = [v for r in conv.values() for v in r["steps_per_tau"]]
        nsteps = max(r["nsteps"] for r in conv.values())
        marker = "\\paragraph{How far the chains can be trusted.}"
        i0 = t.find(marker)
        i1 = t.find("\n\n", i0) if i0 >= 0 else -1
        new_para = (
            "\\paragraph{How far the chains can be trusted.} These chains are "
            "short, so we report the diagnostics instead of asserting convergence. "
            "For the two runs behind Table~\\ref{tab:retrieval} the integrated "
            "autocorrelation times are $\\tau\\simeq%d$--$%d$ steps, so a $%d$-step "
            "chain carries only about $%d$--$%d$ independent samples per walker, and "
            "the effective sample sizes are $%d$--$%d$ per parameter; the medians of "
            "the first and second halves of each post-burn-in chain agree to within "
            "$%.1f$--$%.1f$ posterior standard deviations. That is enough to support "
            "the two claims we take from these runs --- the ordering of the two data "
            "sets in $\\dofs$, and the sign of the cloud--metallicity correlation --- "
            "and not enough to support precise statements about posterior quantiles, "
            "so the medians and $16$--$84\\%%$ intervals in Table~\\ref{tab:retrieval} "
            "should be read as indicative. The quantitative bias numbers of "
            "Section~\\ref{sec:res_cost} do not come from these chains at all. The "
            "validation also covers two of the twelve spectra, both of WASP-39\\,b: it "
            "does not re-derive every horizon value in Table~\\ref{tab:mrt}, and "
            "because it shares PLATON with the diagnostic it cannot speak to "
            "model-systematics differences."
            % (int(min(tau)), int(max(tau)), nsteps, int(min(spw)), int(max(spw)),
               int(min(ess)), int(max(ess)), min(half), max(half)))
        if i0 >= 0 and i1 > i0:
            print("OLD para tail:", t[max(0, i1 - 160):i1].replace("\n", " "))
            print("NEW para tail:", new_para[-160:])
            t = t[:i0] + new_para + t[i1:]
        else:
            print("MISS convergence paragraph")


    open(SEC5, "wb").write(t.encode("utf-8"))
    print("written | changed:", t != raw)


if __name__ == "__main__":
    main()
